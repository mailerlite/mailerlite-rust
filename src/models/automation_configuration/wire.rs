//! Internal serialization and reserved configuration fields.
use serde::Serialize;

pub(crate) fn configuration_fields<T: Serialize>(
    value: &T,
) -> crate::Result<serde_json::Map<String, serde_json::Value>> {
    match serde_json::to_value(value)? {
        serde_json::Value::Object(fields) => Ok(fields),
        _ => Err(crate::Error::Config(
            "automation configuration must be an object".into(),
        )),
    }
}
